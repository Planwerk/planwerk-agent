func TestMaterialize_GitFailureLeavesNothingBehind(t *testing.T) {
	tmp := t.TempDir()
	t.Setenv("TMPDIR", tmp)
	// gitreftest.Repo creates no origin/main, so the range does not resolve.
	dir := gitreftest.Repo(t, map[string]string{"app.go": "package app\n"})

	for _, exclude := range []bool{false, true} {
		d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}, Exclude: exclude})
		cleanup()
		if err == nil || !strings.Contains(err.Error(), "git -c core.quotePath=false") || !strings.Contains(err.Error(), "origin/main...HEAD") {
			t.Errorf("Exclude=%v: err = %v, want an error naming the git command", exclude, err)
		}
		if !reflect.DeepEqual(d, Diff{}) {
			t.Errorf("Exclude=%v: Diff = %+v, want the zero Diff", exclude, d)
		}
	}
	if left := diffDirsIn(t, tmp); len(left) != 0 {
		t.Errorf("TMPDIR holds %v after a failed write, want no diff directory", left)
	}

	d, cleanup := MaterializeOrWarn(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}})
	cleanup()
	if !reflect.DeepEqual(d, Diff{}) {
		t.Errorf("MaterializeOrWarn = %+v, want the zero Diff on a failure", d)
	}
}

// TestRunGit_DoesNotWaitOnAGrandchildHoldingItsOutput pins gitWaitDelay: a
// process git leaves running with the output pipes open, as a lazy fetch in a
// blobless clone can, must not keep runGit waiting until it ends.
func TestRunGit_DoesNotWaitOnAGrandchildHoldingItsOutput(t *testing.T) {
	t.Parallel()
	var out bytes.Buffer
	start := time.Now()
	err := runGit(t.TempDir(), &out, []string{"-c", "alias.hold=!sleep 30 &", "hold"})
	if elapsed := time.Since(start); elapsed > 10*time.Second {
		t.Errorf("runGit returned after %s: the grandchild held it until it ended", elapsed)
	}
	if !errors.Is(err, exec.ErrWaitDelay) {
		t.Errorf("err = %v, want exec.ErrWaitDelay once the pipes were closed", err)
	}
}

// TestCappedWriter_FailsPastTheCap pins the size cap: writes pass through with
// their newlines counted until the cap, and the write that would cross it
// fails without writing anything.
func TestCappedWriter_FailsPastTheCap(t *testing.T) {
	t.Parallel()
	var buf bytes.Buffer
	w := &cappedWriter{w: &buf, max: 8}
	if n, err := w.Write([]byte("ab\ncd\n")); n != 6 || err != nil {
		t.Fatalf("Write under the cap = %d, %v; want 6, nil", n, err)
	}
	if _, err := w.Write([]byte("efg\n")); !errors.Is(err, errDiffTooLarge) {
		t.Fatalf("Write past the cap = %v, want errDiffTooLarge", err)
	}
	if !w.exceeded || w.lines != 2 || buf.String() != "ab\ncd\n" {
		t.Errorf("exceeded = %v, lines = %d, written %q; want true, 2, and only the first write", w.exceeded, w.lines, buf.String())
	}
}
