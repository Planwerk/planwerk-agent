func TestMaterialize_SinceRefDiffsTheWorkingTree(t *testing.T) {
	t.Parallel()
	dir, _ := branchRepo(t,
		map[string]string{"app.go": "package app\n"},
		map[string]string{"app.go": "package app\n\nvar Before = 1\n"},
	)
	fixed := git(t, dir, "rev-parse", "HEAD")
	gitreftest.Write(t, dir, "app.go", "package app\n\nvar After = 2\n")

	d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{fixed}})
	if err != nil {
		t.Fatalf("Materialize: %v", err)
	}
	defer cleanup()
	got := readDiff(t, d)
	if !strings.Contains(got, "-var Before = 1\n") || !strings.Contains(got, "+var After = 2\n") {
		t.Errorf("a re-review diff must compare the working tree with the commit:\n%s", got)
	}
	if d.Range != fixed {
		t.Errorf("Range = %q, want the commit %q", d.Range, fixed)
	}
}

