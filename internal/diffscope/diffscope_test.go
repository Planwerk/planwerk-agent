// generatedHeader is the first line controller-gen writes into a file it
// generates.
const generatedHeader = "// Code generated by controller-gen. DO NOT EDIT.\n"

// git runs git with args in dir under the commit identity gitreftest.Repo
// uses, and returns its trimmed output.
func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@example.com", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@example.com")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

// branchRepo commits base on main, commits head on top of it, points
// origin/main at the base commit the way a pull request clone has it, and
// returns the checkout and the base commit's id.
func branchRepo(t *testing.T, base, head map[string]string) (dir, baseSHA string) {
	t.Helper()
	dir = gitreftest.Repo(t, base)
	baseSHA = git(t, dir, "rev-parse", "HEAD")
	for rel, body := range head {
		gitreftest.Write(t, dir, rel, body)
	}
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-q", "-m", "head")
	git(t, dir, "update-ref", "refs/remotes/origin/main", baseSHA)
	return dir, baseSHA
}

// readDiff returns the content of d's file.
func readDiff(t *testing.T, d Diff) string {
	t.Helper()
	data, err := os.ReadFile(d.File)
	if err != nil {
		t.Fatalf("reading the diff file: %v", err)
	}
	return string(data)
}

// diffDirsIn returns the entries of dir whose name starts with DirPrefix.
func diffDirsIn(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", dir, err)
	}
	var found []string
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), DirPrefix) {
			found = append(found, e.Name())
		}
	}
	return found
}

func TestClassify(t *testing.T) {
	t.Parallel()
	lock := func(p string) report.ExcludedFile {
		return report.ExcludedFile{Path: p, Reason: report.ExcludedLockfile}
	}
	gen := func(p string) report.ExcludedFile {
		return report.ExcludedFile{Path: p, Reason: report.ExcludedGenerated}
	}
	vendored := func(p string, n int) report.ExcludedFile {
		return report.ExcludedFile{Path: p, Reason: report.ExcludedVendored, Files: n}
	}

	for _, tc := range []struct {
		name    string
		files   map[string]string // written into the checkout
		changed []string
		want    []report.ExcludedFile
	}{
		{
			name:    "lock files by base name",
			changed: []string{"app.go", "go.sum", "web/package-lock.json"},
			want:    []report.ExcludedFile{lock("go.sum"), lock("web/package-lock.json")},
		},
		{
			name:    "a vendored directory is one entry with its file count",
			changed: []string{"app.go", "vendor/a/b.go", "vendor/c.go"},
			want:    []report.ExcludedFile{vendored("vendor/", 2)},
		},
		{
			name:    "a nested node_modules directory",
			changed: []string{"app.go", "web/node_modules/x/i.js"},
			want:    []report.ExcludedFile{vendored("web/node_modules/", 1)},
		},
		{
			name:    "a generated file",
			files:   map[string]string{"api/zz_generated.deepcopy.go": generatedHeader + "\npackage api\n"},
			changed: []string{"app.go", "api/zz_generated.deepcopy.go"},
			want:    []report.ExcludedFile{gen("api/zz_generated.deepcopy.go")},
		},
		{
			name:    "a leading comment block after blank lines and a shebang",
			files:   map[string]string{"gen.sh": "#!/bin/sh\n\n# Code generated by stringer. DO NOT EDIT.\necho hi\n"},
			changed: []string{"app.go", "gen.sh"},
			want:    []report.ExcludedFile{gen("gen.sh")},
		},
		{
			name:    "the marker in a template after the package clause is not generated",
			files:   map[string]string{"gen/template.go": "package gen\n\nconst header = `" + generatedHeader + "`\n"},
			changed: []string{"app.go", "gen/template.go"},
		},
		{
			name:    "a test carrying the marker stays (decision 16)",
			files:   map[string]string{"foo_test.go": generatedHeader + "\npackage foo\n"},
			changed: []string{"app.go", "foo_test.go"},
		},
		{
			name:    "a vendor directory under testdata is a fixture",
			changed: []string{"app.go", "testdata/vendor/x.go"},
		},
		{
			name:    "a test directory keeps its lock file",
			changed: []string{"app.go", "tests/fixture/go.sum"},
		},
		{
			name:    "a test under a vendored directory is vendored code",
			changed: []string{"app.go", "vendor/x/x_test.go", "node_modules/pkg/test/index.js"},
			want:    []report.ExcludedFile{vendored("node_modules/", 1), vendored("vendor/", 1)},
		},
		{
			name:    "a lock or generated file with a control character in its path stays",
			files:   map[string]string{"gen\tx.go": generatedHeader},
			changed: []string{"app.go", "x\ty/go.sum", "gen\tx.go"},
		},
		{
			name:    "a vendored directory with a control character in its path stays",
			changed: []string{"app.go", "a\nb/vendor/x.go"},
		},
		{
			// The directory's pathspec leaves the file out, so it must count.
			name:    "a file with a control character counts toward its vendored directory",
			changed: []string{"app.go", "vendor/c.go", "vendor/a\tb.go"},
			want:    []report.ExcludedFile{vendored("vendor/", 2)},
		},
		{
			name:    "a change made only of vendored files, one with a control character, is diffed in full",
			changed: []string{"vendor/c.go", "vendor/a\tb.go"},
		},
		{
			name:    "a change made only of excluded files is diffed in full",
			changed: []string{"go.sum"},
		},
		{
			name:    "entries are sorted by path",
			files:   map[string]string{"zz_generated.go": generatedHeader},
			changed: []string{"zz_generated.go", "vendor/x.go", "app.go", "go.sum", "Cargo.lock"},
			want:    []report.ExcludedFile{lock("Cargo.lock"), lock("go.sum"), vendored("vendor/", 1), gen("zz_generated.go")},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			gitreftest.Write(t, dir, "app.go", "package app\n")
			for rel, body := range tc.files {
				gitreftest.Write(t, dir, rel, body)
			}
			if got := Classify(dir, tc.changed); !reflect.DeepEqual(got, tc.want) {
				t.Errorf("Classify(%q) = %+v, want %+v", tc.changed, got, tc.want)
			}
		})
	}

	t.Run("a symlink to a generated file is not generated", func(t *testing.T) {
		t.Parallel()
		dir := t.TempDir()
		gitreftest.Write(t, dir, "real/zz_generated.go", generatedHeader)
		if err := os.Symlink(filepath.Join(dir, "real", "zz_generated.go"), filepath.Join(dir, "link.go")); err != nil {
			t.Fatal(err)
		}
		if got := Classify(dir, []string{"app.go", "link.go"}); got != nil {
			t.Errorf("Classify = %+v, want nil: a symlink is never opened", got)
		}
	})
}

func TestIsExcludedAndReviewable(t *testing.T) {
	t.Parallel()
	excluded := []report.ExcludedFile{
		{Path: "go.sum", Reason: report.ExcludedLockfile},
		{Path: "web/node_modules/", Reason: report.ExcludedVendored, Files: 2},
	}
	for p, want := range map[string]bool{
		"go.sum":                  true,
		"web/node_modules/x/i.js": true,
		"api/go.sum":              false,
		"web/node_modules.js":     false,
		"app.go":                  false,
	} {
		if got := IsExcluded(p, excluded); got != want {
			t.Errorf("IsExcluded(%q) = %v, want %v", p, got, want)
		}
	}
	files := []string{"app.go", "go.sum", "web/node_modules/x/i.js", "web/main.js"}
	if got, want := Reviewable(files, excluded), []string{"app.go", "web/main.js"}; !reflect.DeepEqual(got, want) {
		t.Errorf("Reviewable = %q, want %q", got, want)
	}
	if got := Reviewable(files, nil); !reflect.DeepEqual(got, files) {
		t.Errorf("Reviewable without exclusions = %q, want every file", got)
	}
}

func TestMaterialize_WritesTheBranchDiffWithoutExcludedFiles(t *testing.T) {
	t.Parallel()
	dir, _ := branchRepo(t,
		map[string]string{"app.go": "package app\n", "go.sum": "a v1\n", "vendor/x/y.go": "package x\n"},
		map[string]string{"app.go": "package app\n\nfunc New() {}\n", "go.sum": "a v2\n", "vendor/x/y.go": "package x\n\nvar Y = 1\n"},
	)

	d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}, Exclude: true})
	if err != nil {
		t.Fatalf("Materialize: %v", err)
	}
	if !strings.HasPrefix(filepath.Base(d.Dir), DirPrefix) || !filepath.IsAbs(d.Dir) || d.File != filepath.Join(d.Dir, "branch.diff") {
		t.Fatalf("Diff = %+v, want an absolute %s directory holding branch.diff", d, DirPrefix)
	}
	got := readDiff(t, d)
	if !strings.Contains(got, "diff --git a/app.go b/app.go\n") || !strings.Contains(got, "+func New() {}\n") {
		t.Errorf("the diff must carry the app.go change:\n%s", got)
	}
	if strings.Contains(got, "go.sum") || strings.Contains(got, "vendor/") {
		t.Errorf("the diff must leave out the excluded files:\n%s", got)
	}
	if d.Range != "origin/main...HEAD" || d.Lines != strings.Count(got, "\n") {
		t.Errorf("Range = %q, Lines = %d; want origin/main...HEAD and the file's %d newlines", d.Range, d.Lines, strings.Count(got, "\n"))
	}
	want := []report.ExcludedFile{
		{Path: "go.sum", Reason: report.ExcludedLockfile},
		{Path: "vendor/", Reason: report.ExcludedVendored, Files: 1},
	}
	if !reflect.DeepEqual(d.Excluded, want) {
		t.Errorf("Excluded = %+v, want %+v", d.Excluded, want)
	}
	if info, err := os.Stat(d.File); err != nil || info.Mode().Perm() != 0o600 {
		t.Errorf("stat %s = %v, %v; want mode 0600", d.File, info, err)
	}

	cleanup()
	if _, err := os.Stat(d.Dir); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("after cleanup, stat %s = %v, want not exist", d.Dir, err)
	}
	cleanup() // a second call must be harmless
}

// TestMaterialize_SubdirectoryRepoDirDiffsTheWholeChange pins that git runs at
// the top level: run from a subdirectory, the `.` pathspec would narrow the
// diff to it, and the root-relative paths git lists would name the wrong files.
func TestMaterialize_SubdirectoryRepoDirDiffsTheWholeChange(t *testing.T) {
	t.Parallel()
	dir, _ := branchRepo(t,
		map[string]string{"app.go": "package app\n", "go.sum": "a v1\n", "sub/x.go": "package sub\n"},
		map[string]string{"app.go": "package app\n\nvar A = 1\n", "go.sum": "a v2\n", "sub/x.go": "package sub\n\nvar X = 1\n", "zz_generated.go": generatedHeader + "\npackage app\n"},
	)

	d, cleanup, err := Materialize(Request{RepoDir: filepath.Join(dir, "sub"), Revs: []string{"origin/main...HEAD"}, Exclude: true})
	if err != nil {
		t.Fatalf("Materialize: %v", err)
	}
	defer cleanup()
	got := readDiff(t, d)
	for _, file := range []string{"app.go", "sub/x.go"} {
		if !strings.Contains(got, "diff --git a/"+file+" b/"+file+"\n") {
			t.Errorf("the diff must carry %s, inside the subdirectory or not:\n%s", file, got)
		}
	}
	if strings.Contains(got, "go.sum") || strings.Contains(got, "zz_generated.go") {
		t.Errorf("the diff must leave out the excluded files:\n%s", got)
	}
	want := []report.ExcludedFile{
		{Path: "go.sum", Reason: report.ExcludedLockfile},
		{Path: "zz_generated.go", Reason: report.ExcludedGenerated},
	}
	if !reflect.DeepEqual(d.Excluded, want) {
		t.Errorf("Excluded = %+v, want %+v: the generated header must be read at the top level", d.Excluded, want)
	}
}

// TestMaterialize_CountsAControlCharacterFileUnderAVendoredDirectory pins that
// a file the vendored directory's pathspec removes is counted whatever its
// name holds, so the entry's count matches the diff and a change made only of
// vendored files is diffed in full.
func TestMaterialize_CountsAControlCharacterFileUnderAVendoredDirectory(t *testing.T) {
	t.Parallel()
	base := map[string]string{"app.go": "package app\n"}

	t.Run("beside a file that stays", func(t *testing.T) {
		t.Parallel()
		dir, _ := branchRepo(t, base, map[string]string{"app.go": "package app\n\nvar A = 1\n", "vendor/c.go": "package v\n", "vendor/a\tb.go": "package v\n"})
		d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}, Exclude: true})
		if err != nil {
			t.Fatalf("Materialize: %v", err)
		}
		defer cleanup()
		if want := []report.ExcludedFile{{Path: "vendor/", Reason: report.ExcludedVendored, Files: 2}}; !reflect.DeepEqual(d.Excluded, want) {
			t.Errorf("Excluded = %+v, want %+v", d.Excluded, want)
		}
		if got := readDiff(t, d); !strings.Contains(got, "diff --git a/app.go b/app.go\n") || strings.Contains(got, "vendor/") {
			t.Errorf("the diff must carry app.go and nothing under vendor/:\n%s", got)
		}
	})

	t.Run("alone", func(t *testing.T) {
		t.Parallel()
		dir, _ := branchRepo(t, base, map[string]string{"vendor/c.go": "package v\n", "vendor/a\tb.go": "package v\n"})
		d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}, Exclude: true})
		if err != nil {
			t.Fatalf("Materialize: %v", err)
		}
		defer cleanup()
		if d.Excluded != nil {
			t.Errorf("Excluded = %+v, want nil for a change made only of vendored files", d.Excluded)
		}
		// git quotes a name with a control character even with
		// core.quotePath=false.
		if got := readDiff(t, d); !strings.Contains(got, "diff --git a/vendor/c.go b/vendor/c.go\n") || !strings.Contains(got, `vendor/a\tb.go`) {
			t.Errorf("the diff must carry both vendored files in full:\n%s", got)
		}
	})
}

func TestMaterialize_IgnoresDiffDriversTextconvAndColor(t *testing.T) {
	t.Parallel()
	dir, _ := branchRepo(t,
		map[string]string{"app.go": "package app\n", ".gitattributes": "*.go diff=upper\n"},
		map[string]string{"app.go": "package app\n\nfunc lower() {}\n"},
	)
	// Repo-local configuration standing in for the operator's.
	git(t, dir, "config", "diff.external", "/bin/false")
	git(t, dir, "config", "color.diff", "always")
	git(t, dir, "config", "diff.upper.textconv", "tr a-z A-Z <")
	git(t, dir, "config", "diff.noprefix", "true")

	// The premise: a session's own git diff, even with --no-ext-diff, sees the
	// text conversion and the color the configuration asks for.
	plain := git(t, dir, "diff", "--no-ext-diff", "origin/main...HEAD")
	if !strings.Contains(plain, "FUNC LOWER") || !strings.Contains(plain, "\x1b[") {
		t.Fatalf("the configuration does not take effect, so the test proves nothing:\n%q", plain)
	}

	d, cleanup, err := Materialize(Request{RepoDir: dir, Revs: []string{"origin/main...HEAD"}})
	if err != nil {
		t.Fatalf("Materialize: %v", err)
	}
	defer cleanup()
	got := readDiff(t, d)
	if !strings.Contains(got, "+func lower() {}\n") || !strings.Contains(got, "diff --git a/app.go b/app.go\n") {
		t.Errorf("the diff must hold the original lines with a/ and b/ prefixes:\n%q", got)
	}
	if strings.Contains(got, "FUNC") || strings.Contains(got, "\x1b") {
		t.Errorf("the diff must carry no text conversion and no color:\n%q", got)
	}
}

